def bom_prices():
    """Локальная копия списка с ценами (private/ в .gitignore). Нет prices.json — пропускаем."""
    if not os.path.exists(PRICES_FILE):
        return None, None
    with open(PRICES_FILE) as f:
        pr = json.load(f)
    md = ["# Список покупок с ценами (локально, не публикуется)", "", f"Источник: {pr['source']}.", "",
          "| № | Позиция | Модель | Цена, ₽ | Кол-во | Сумма, ₽ | Статус |", "|---:|---|---|---:|---:|---:|---|"]
    total = 0
    for no, sec, name, model, use, unit, q in ESTIMATE:
        e = pr["estimate"][str(no)]
        total += e["price"] * q
        md.append(f"| {no} | {name} | {model} | {e['price']} | {q} | {e['price'] * q} | {e['status']} |")
    if total != pr["total"]:
        raise SystemExit(f"[docs] сумма {total} ≠ {pr['total']} в prices.json")
    extra = sum(pr["extra"])
    md += [f"| | **ИТОГО** | | | | **{total}** | |", "", "## Дополнительно (ориентир)", ""]
    md += [f"- {a.split(':')[0]} — {c} ₽" for (a, _, _), c in zip(NOT_IN_ESTIMATE, pr["extra"])]
    md += ["", f"Торсионные пружины: {pr['spring_wire_note']}.", "",
           f"**Всего ≈ {total + extra} ₽** (без питания)."]
    with open(os.path.join(BASE, "private", "bom_prices.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    return total, extra


